"""The Dumbest Thing Your Agent Did Today entry.

Writes one original line about the dumbest thing my agent did today to
``$MAKEFUN_OUTPUT_DIR/entry.txt`` (default ``/output``).
Python 3.13 standard library only; no network, no randomness.
"""

import os

LINE = (
    "My agent downloaded the bounty kit, unpacked it into a folder "
    "inside the folder, then confidently announced the CLI was missing."
)


def main() -> None:
    output_dir = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
    os.makedirs(output_dir, exist_ok=True)
    with open(os.path.join(output_dir, "entry.txt"), "w", encoding="utf-8") as f:
        f.write(LINE)


if __name__ == "__main__":
    main()
